"""第三版定稿的双单行提示词；模式标记仅用于内部拼装，不进入模型转录。"""
from __future__ import annotations

import re


# %...% 仅 Runs，#...# 仅 completions；只处理本模块静态模板，不处理用户文本。
_MODE_LINE = re.compile(r"(?m)^([%#])(.*?)\1\n?")


def render_mode_text(template: str, *, runs: bool) -> str:
    return _MODE_LINE.sub(
        lambda match: match[2] + "\n" if (match[1] == "%") == runs else "", template,
    )


