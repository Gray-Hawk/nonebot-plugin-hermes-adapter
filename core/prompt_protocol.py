def render_decision_protocol(*, runs: bool, group_rules: str | None = None) -> str:
    private = group_rules is None
    head = (
        "你处于私聊对话。是否回复由你自己决定：有实质内容的消息正常回应；无特殊含义的纯表情、无意义刷屏，或你判断无需回应时，让 body 留空。\n\n"
        if private else "你处于群活跃态。每条新消息都需要决定是否要插话。\n\n"
    )
    scope = (
        "私聊只有对方一个人，不必 @ 任何人，正文里不要写 [CQ:at,...] 标记。\n"
        if private else group_rules
    )
    return (
        "<decision_protocol>\n" + head + render_mode_text(_PROTOCOL, runs=runs)
        + "\n" + scope
        + "每轮最终输出仍必须至少有一份完整决策；没有要说的就输出一份空 body，不附其他文字。\n"
        + "</decision_protocol>"
    )


